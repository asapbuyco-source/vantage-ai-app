





export type Language = 'en' | 'fr' | 'es' | 'pt';

/** Inline string picker for all supported languages.
 *  Spanish/Portuguese fall back to English when not provided. */
export const translate = (language: string, fr: string, en: string, es?: string, pt?: string): string => {
  if (language === 'fr') return fr;
  if (language === 'es') return es ?? en;
  if (language === 'pt') return pt ?? en;
  return en;
};

